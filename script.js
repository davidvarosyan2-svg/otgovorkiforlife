let currentCategory = Object.keys(excuses)[0];
let lastIndex = -1;

const categoriesEl = document.getElementById("categories");
const selectedTopic = document.getElementById("selectedTopic");
const generateBtn = document.getElementById("generateBtn");
const resultBox = document.getElementById("resultBox");
const excuseEl = document.getElementById("excuse");
const anotherBtn = document.getElementById("anotherBtn");
const copyStatus = document.getElementById("copyStatus");

function renderCategories() {
  categoriesEl.innerHTML = "";

  Object.keys(excuses).forEach((category, index) => {
    const button = document.createElement("button");
    button.className = "category" + (index === 0 ? " active" : "");
    button.type = "button";
    button.setAttribute("role", "tab");
    button.textContent = category;
    button.addEventListener("click", () => selectCategory(category, button));
    categoriesEl.appendChild(button);
  });

  updateTopic();
}

function updateTopic() {
  selectedTopic.textContent = "Сейчас выбрано: " + currentCategory;
}

function selectCategory(category, button) {
  currentCategory = category;
  document.querySelectorAll(".category").forEach(el => el.classList.remove("active"));
  button.classList.add("active");
  updateTopic();
  resetGenerator();
  button.scrollIntoView({ behavior: "smooth", block: "nearest", inline: "center" });
}

function randomExcuse() {
  const list = excuses[currentCategory];
  let index;

  do {
    index = Math.floor(Math.random() * list.length);
  } while (list.length > 1 && index === lastIndex);

  lastIndex = index;
  return list[index];
}

function showExcuse() {
  excuseEl.textContent = randomExcuse();
  copyStatus.textContent = "";
  generateBtn.classList.add("hidden");
  resultBox.classList.remove("hidden");
}

function resetGenerator() {
  lastIndex = -1;
  generateBtn.classList.remove("hidden");
  resultBox.classList.add("hidden");
  excuseEl.textContent = "";
  copyStatus.textContent = "";
}

async function copyExcuse() {
  const text = excuseEl.textContent;
  if (!text) return;

  try {
    await navigator.clipboard.writeText(text);
  } catch {
    const area = document.createElement("textarea");
    area.value = text;
    area.style.position = "fixed";
    area.style.opacity = "0";
    document.body.appendChild(area);
    area.select();
    document.execCommand("copy");
    area.remove();
  }

  copyStatus.textContent = "✓ Скопировано";
  setTimeout(() => {
    copyStatus.textContent = "";
  }, 1400);
}

generateBtn.addEventListener("click", showExcuse);
anotherBtn.addEventListener("click", showExcuse);
excuseEl.addEventListener("click", copyExcuse);

renderCategories();
